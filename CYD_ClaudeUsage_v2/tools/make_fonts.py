#!/usr/bin/env python3
"""
make_fonts.py — rasterise TrueType fonts into anti-aliased glyph tables
for the Claude Monitor firmware (writes ../fonts.h).

Needs Pillow:   python3 -m pip install pillow
Run:            python3 tools/make_fonts.py

Uses DM Sans (SIL Open Font License) from ~/Library/Fonts by default.
Override the folder with FONT_DIR=/path/to/fonts.
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

FONT_DIR = os.environ.get("FONT_DIR", os.path.expanduser("~/Library/Fonts"))
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fonts.h")

ASCII = "".join(chr(c) for c in range(32, 127))
EXTRA = "·–…•"          # ·  –  …  •
DIGITS = "0123456789%-"

# name, file, pixel size, character set
FONTS = [
    ("F_SMALL", "DMSans_18pt-Medium.ttf",   19, ASCII + EXTRA),
    ("F_BODY",  "DMSans_18pt-SemiBold.ttf", 23, ASCII + EXTRA),
    ("F_LARGE", "DMSans_24pt-SemiBold.ttf", 31, ASCII + EXTRA),
    ("F_HERO",  "DMSans_36pt-SemiBold.ttf", 58, DIGITS),
    ("F_GIANT", "DMSans_36pt-SemiBold.ttf", 124, DIGITS),
]


def build(name, fname, size, chars):
    path = os.path.join(FONT_DIR, fname)
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    cap = font.getbbox("H", anchor="ls")
    dig = font.getbbox("0", anchor="ls")
    glyphs, data = [], bytearray()
    for ch in chars:
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        adv4 = int(round(font.getlength(ch) * 4))
        off = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            data += img.tobytes()
        glyphs.append((ord(ch), w, h, x0, y0, adv4, off))
    return {
        "name": name, "file": fname, "size": size,
        "ascent": ascent, "descent": descent,
        "cap": -cap[1], "digit": -dig[1],
        "glyphs": glyphs, "data": data,
    }


def emit(fonts):
    out = []
    out.append("// fonts.h — GENERATED by tools/make_fonts.py. Do not edit by hand.")
    out.append("// Typeface: DM Sans (SIL Open Font License 1.1).")
    out.append("#pragma once")
    out.append('#include "gfx.h"\n')
    total = 0
    for f in fonts:
        n = f["name"]
        out.append(f"// {n}: {f['file']} @ {f['size']}px, {len(f['glyphs'])} glyphs, {len(f['data'])} bytes")
        out.append(f"static const uint8_t {n}_bits[] = {{")
        d = f["data"]
        for i in range(0, len(d), 32):
            out.append("  " + ",".join(str(b) for b in d[i:i + 32]) + ",")
        if not d:
            out.append("  0")
        out.append("};")
        out.append(f"static const GfxGlyph {n}_glyphs[] = {{")
        for (code, w, h, xo, yo, adv4, off) in f["glyphs"]:
            out.append(f"  {{{code},{w},{h},{xo},{yo},{adv4},{off}}},")
        out.append("};")
        out.append(
            f"static const GfxFont {n} = {{ {n}_bits, {n}_glyphs, {len(f['glyphs'])}, "
            f"{f['ascent']}, {f['descent']}, {f['cap']}, {f['digit']} }};\n"
        )
        total += len(d) + 12 * len(f["glyphs"])
    out.append(f"// Total font data: ~{total // 1024} KB")
    with open(OUT, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {os.path.normpath(OUT)}  (~{total // 1024} KB)")


if __name__ == "__main__":
    missing = [f for (_, f, _, _) in FONTS if not os.path.exists(os.path.join(FONT_DIR, f))]
    if missing:
        sys.exit(f"Missing fonts in {FONT_DIR}: {missing}")
    emit([build(*spec) for spec in FONTS])
